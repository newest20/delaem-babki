    """Генерация случайного имени"""
    first_names = ['Александр', 'Михаил', 'Дмитрий', 'Андрей', 'Сергей', 'Алексей']
    last_names = ['Иванов', 'Петров', 'Сидоров', 'Смирнов', 'Кузнецов', 'Попов']
    return f"{random.choice(first_names)} {random.choice(last_names)}"

